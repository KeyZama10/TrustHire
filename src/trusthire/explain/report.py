"""PDF integrity report (ReportLab): trust score, risk timeline, alerts, module evidence, Grad-CAM frames,
audio saliency, fusion attributions, transcript excerpts and an LLM-written summary."""

from __future__ import annotations

import io
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import Image, PageBreak, Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

MODULE_LABELS = {
    "video_deepfake": "Video deepfake",
    "voice_spoof": "Synthetic voice",
    "av_sync": "Lip-sync",
    "face_identity": "Face identity",
    "voice_identity": "Voice identity",
    "behavior": "Gaze / second screen",
    "liveness": "Liveness (rPPG)",
    "objects": "Objects / people",
    "scripted_answer": "Scripted answer",
    "resume_consistency": "Resume consistency",
}


def _img(png: bytes, width_mm: float) -> Image:
    im = Image(io.BytesIO(png))
    ratio = im.imageHeight / im.imageWidth
    im.drawWidth = width_mm * mm
    im.drawHeight = width_mm * mm * ratio
    return im


def _esc(s: str) -> str:
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def build_pdf(
    session: dict[str, Any],
    summary: str,
    summary_provider: str,
    figures: dict[str, bytes],
    frames: list[tuple[float, bytes, float]],
    out: str | Path,
) -> Path:
    out = Path(out)
    ss = getSampleStyleSheet()
    h1, h2, body = ss["Title"], ss["Heading2"], ss["BodyText"]
    small = ParagraphStyle("small", parent=body, fontSize=8, leading=10, textColor=colors.grey)
    doc = SimpleDocTemplate(
        str(out),
        pagesize=A4,
        leftMargin=16 * mm,
        rightMargin=16 * mm,
        topMargin=14 * mm,
        bottomMargin=14 * mm,
        title="TrustHire integrity report",
    )
    el: list[Any] = []
    trust = session.get("trust", {})
    ts = trust.get("trust_score")
    band = (
        "LOW RISK"
        if ts is not None and ts >= 70
        else "REVIEW"
        if ts is not None and ts >= 45
        else "HIGH RISK"
    )
    band_col = {"LOW RISK": "#27ae60", "REVIEW": "#e67e22", "HIGH RISK": "#c0392b"}[band]
    el.append(Paragraph("TrustHire — Interview Integrity Report", h1))
    el.append(
        Paragraph(
            f"Candidate: <b>{_esc(session.get('candidate', '—'))}</b> &nbsp; Session: {session.get('id')} &nbsp; "
            f"Duration: {session.get('duration_s', 0):.0f} s &nbsp; Generated: {datetime.now(UTC):%Y-%m-%d %H:%M} UTC",
            body,
        )
    )
    el.append(Spacer(1, 4 * mm))
    el.append(
        Table(
            [
                [
                    Paragraph(
                        f"<font size=22 color='{band_col}'><b>{ts}</b></font><br/>trust score / 100", body
                    ),
                    Paragraph(
                        f"<font size=14 color='{band_col}'><b>{band}</b></font><br/>"
                        f"session risk {trust.get('session_risk')} · peak {trust.get('peak_risk')} · "
                        f"flagged {100 * (trust.get('flagged_fraction') or 0):.0f}% of windows",
                        body,
                    ),
                ]
            ],
            colWidths=[45 * mm, 130 * mm],
            style=TableStyle(
                [("BOX", (0, 0), (-1, -1), 0.6, colors.lightgrey), ("VALIGN", (0, 0), (-1, -1), "MIDDLE")]
            ),
        )
    )
    el.append(Spacer(1, 4 * mm))
    el.append(Paragraph("Summary", h2))
    for para in summary.split("\n"):
        if para.strip():
            el.append(Paragraph(_esc(para.strip()), body))
    el.append(
        Paragraph(
            f"Summary generated by: {summary_provider}. Automated evidence — not a determination of fraud; "
            "decisions require human review.",
            small,
        )
    )
    if "timeline" in figures:
        el.append(Paragraph("Risk timeline", h2))
        el.append(_img(figures["timeline"], 175))
    # module table
    el.append(Paragraph("Per-module evidence", h2))
    rows = [["Module", "Mean risk", "Max risk", "Coverage", "Windows flagged"]]
    for m, st in session.get("module_stats", {}).items():
        rows.append(
            [
                MODULE_LABELS.get(m, m),
                f"{st['mean']:.2f}",
                f"{st['max']:.2f}",
                f"{100 * st['coverage']:.0f}%",
                str(st["flagged"]),
            ]
        )
    t = Table(rows, colWidths=[55 * mm, 25 * mm, 25 * mm, 25 * mm, 35 * mm])
    t.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#1f4e79")),
                ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
                ("FONTSIZE", (0, 0), (-1, -1), 8),
                ("GRID", (0, 0), (-1, -1), 0.3, colors.lightgrey),
            ]
        )
    )
    el.append(t)
    alerts = session.get("alerts", [])
    if alerts:
        el.append(Paragraph("Alerts", h2))
        ar = [["Time", "Severity", "Module", "Message"]] + [
            [
                f"{a['t']:.1f}s",
                a["severity"],
                MODULE_LABELS.get(a["module"], a["module"]),
                Paragraph(_esc(a["message"]), body),
            ]
            for a in alerts[:40]
        ]
        at = Table(ar, colWidths=[18 * mm, 20 * mm, 35 * mm, 102 * mm])
        at.setStyle(
            TableStyle(
                [
                    ("FONTSIZE", (0, 0), (-1, -1), 8),
                    ("GRID", (0, 0), (-1, -1), 0.3, colors.lightgrey),
                    ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#eeeeee")),
                ]
            )
        )
        el.append(at)
    el.append(PageBreak())
    if frames:
        el.append(Paragraph("Flagged frames (Grad-CAM on the 'fake' class)", h2))
        cells = [
            [_img(png, 52), Paragraph(f"t={t:.1f}s<br/>P(fake)={p:.2f}", small)] for t, png, p in frames[:6]
        ]
        grid: list[list[Any]] = []
        for i in range(0, len(cells), 2):
            right = cells[i + 1] if i + 1 < len(cells) else ["", ""]
            grid.append([*cells[i], *right])
        el.append(Table(grid, colWidths=[55 * mm, 30 * mm, 55 * mm, 30 * mm]))
    if "audio_saliency" in figures:
        el.append(Paragraph("Most suspicious audio segment (occlusion saliency)", h2))
        el.append(_img(figures["audio_saliency"], 170))
    if "contributions" in figures:
        el.append(Paragraph("Fusion attribution for the highest-risk window", h2))
        el.append(_img(figures["contributions"], 140))
    answers = session.get("answers", [])
    if answers:
        el.append(Paragraph("Transcript analysis", h2))
        for a in answers[:8]:
            f = a.get("features", {})
            el.append(
                Paragraph(
                    f"<b>{a['t_start']:.0f}–{a['t_end']:.0f}s</b> scripted-risk {a.get('scripted_score', 0):.2f} · "
                    f"fillers/100w {f.get('filler_per_100w', 0):.1f} · gap CV {f.get('gap_cv', 0):.2f} · "
                    f"AI-text {a.get('ai_text_prob') if a.get('ai_text_prob') is not None else 'n/a'}",
                    small,
                )
            )
            el.append(Paragraph(_esc(a.get("text", "")[:600]), body))
    el.append(Spacer(1, 6 * mm))
    el.append(
        Paragraph(
            "Method & limitations: scores come from pretrained detectors (see model cards) fused by a "
            f"{session.get('fusion_method', 'weighted')} model. Detectors can err under poor lighting, low "
            "bandwidth, heavy compression, unusual accents or atypical speaking styles; see docs/LIMITATIONS.md.",
            small,
        )
    )
    doc.build(el)
    return out
